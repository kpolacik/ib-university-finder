export const LANGUAGE_KEY = 'ib-university-finder:language';
const validLanguage = (value) => value === 'sk' || value === 'en';
// English is the default (Jakub, 2026-11-04); Slovak is one click away and
// a stored choice or ?ui=sk still wins.
let language = 'en';
let addressLanguage = false;

export const getLanguage = () => language;
// "2 915" / "2,915": every programme count the page prints goes through here.
export const formatCount = (value) => new Intl.NumberFormat(language === 'sk' ? 'sk-SK' : 'en-IE').format(value);

// `lang` is the teaching-language filter (`?lang=English`), so the interface
// language has its own parameter, `?ui=sk|en`. Never read or write `lang` here.
export function initLanguage(query = '', storage) {
  const fromUrl = new URLSearchParams(query).getAll('ui').find(validLanguage);
  let stored;
  try { stored = (storage ?? globalThis.localStorage)?.getItem(LANGUAGE_KEY); } catch { /* Private browsing. */ }
  language = fromUrl || (validLanguage(stored) ? stored : 'en');
  addressLanguage = Boolean(fromUrl);
  return language;
}

export function setLanguage(value, storage) {
  if (!validLanguage(value)) return;
  language = value;
  addressLanguage = true;
  try { (storage ?? globalThis.localStorage)?.setItem(LANGUAGE_KEY, value); } catch { /* The switch still works. */ }
}

export function languageQuery(query) {
  // Do not re-encode list commas: readSharedList splits raw commas before
  // decoding ids, so URLSearchParams.toString() would change the list itself.
  const parts = String(query).replace(/^\?/, '').split('&').filter(Boolean)
    .filter((part) => !new URLSearchParams(part).has('ui'));
  if (addressLanguage) parts.push(`ui=${language}`);
  return parts.join('&');
}

// Also used by CSV export: its data cells always say the English facts.
export function inLanguage(value, read) {
  const previous = language;
  language = value;
  try { return read(); } finally { language = previous; }
}

export function t(key, vars = {}) {
  let value = UI[language][key] || UI.en[key];
  if (value === undefined) throw new Error(`Unknown i18n key: ${key}`);
  if (typeof value === 'object') {
    const count = vars.count;
    const form = count === 1 ? 'one' : Number.isInteger(count) && count >= 2 && count <= 4 ? 'few' : 'other';
    value = value[form] || value.other;
  }
  return value.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

export function applyLanguage(root = document) {
  root.documentElement.lang = language;
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.getAttribute('data-i18n'));
  for (const node of root.querySelectorAll('[data-i18n-attr]')) {
    for (const pair of node.getAttribute('data-i18n-attr').split(';')) {
      const [attr, key] = pair.split(':');
      node.setAttribute(attr, t(key));
    }
  }
  for (const button of root.querySelectorAll('[data-language]')) {
    button.setAttribute('aria-pressed', String(button.getAttribute('data-language') === language));
  }
}

// Cache both locales, but choose at format time so imported formatters switch.
export function dateFormatter(options) {
  const formats = { en: new Intl.DateTimeFormat('en-GB', options), sk: new Intl.DateTimeFormat('sk-SK', options) };
  return { format: (date) => formats[language].format(date) };
}

export const normaliseEnglish = (text) => String(text ?? '').replace(/\s+/g, ' ').trim();
export const DATA_FIELDS = {
  subject_area: 'subjectAreas', degree_type: 'degreeType', application_system: 'applicationSystem',
  living_cost_source: 'livingCostSource', admission: 'admission', english_requirement: 'englishRequirement',
  baseline_requirement: 'baselineRequirement',
};
let translations = new Map();
let searchCache = new WeakMap();

export function setDataTranslations(rows = []) {
  searchCache = new WeakMap();
  translations = new Map(rows.filter((row) => row.sk?.trim()).map((row) => [
    `${row.field}\u0000${normaliseEnglish(row.en)}`, row.sk,
  ]));
}

// A whole-cell match wins. Otherwise translate list items separately, keeping
// the original separators and the English for each piece available to reveal.
export function dataParts(field, english, lang = language) {
  const en = normaliseEnglish(english);
  if (!en) return [];
  if (lang === 'en') return [{ text: String(english) }];
  const sk = translations.get(`${field}\u0000${en}`)
    || (['admission', 'english_requirement'].includes(field) ? translations.get(`${field}_default\u0000${en}`) : null);
  if (sk) return normaliseEnglish(sk) === en ? [{ text: sk }] : [{ text: sk, en }];
  if (/ · |;/.test(en)) return en.split(/( · |;\s*)/).filter(Boolean).flatMap((item, i) =>
    i % 2 ? [{ text: item }] : dataParts(field, item, lang));
  return [{ text: en, missing: true }];
}

// Search is bilingual in either interface language. Never rewrite parsed
// facts or the English search blob: points, costs and sorting keep their input.
export function translatedSearchText(row) {
  if (searchCache.has(row)) return searchCache.get(row);
  const text = Object.entries(DATA_FIELDS).flatMap(([field, prop]) => {
    const values = Array.isArray(row[prop]) ? row[prop] : [row[prop]];
    return values.flatMap((value) => dataParts(field, value, 'sk').map((part) => part.text));
  }).join(' ');
  searchCache.set(row, text);
  return text;
}

export function facetLabel(value) {
  const key = `facet_${value.toLowerCase().replaceAll(' ', '_')}`;
  return Object.hasOwn(UI.en, key) ? t(key) : value;
}
